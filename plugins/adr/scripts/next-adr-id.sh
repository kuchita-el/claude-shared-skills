#!/usr/bin/env bash
# ADR 識別子の発番器
#
# ADR_DIR 配下の既存 ADR を見て、次に起票する ADR の識別子
# `ADR-YYYYMMDDHHMM-NN` を stdout へ1行で出力する（slug は呼び出し側が付与する）。
#
# 時刻部（YYYYMMDDHHMM）は作業者のローカル時刻から取り、連番部（NN）は
# 同一時刻部を持つ既存ファイルの最大番号 + 1 とする（既存が無ければ 01）。
# 時刻部が並行ブランチ間の一意性を担い、連番部が同一分内のバースト
# （多決定 ADR の分割で後継を同時に起票する等）の順序を担う。
# 配置ディレクトリ全体・同日全体の最大番号は見ない。日単位で最大 + 1 を取ると
# 並行ブランチがそれぞれ自分の base に対して正しく発番しても同一識別子を生むため。
#
# この根拠は実測にある。2026-07-26、2本の PR がそれぞれ自分の base に対して当時の手順
# （対象日のファイルを列挙して最大 + 1）を正しく実行し、双方が -01 / -02 / -03 を発番した結果、
# 同一識別子が2組ずつ corpus に残った。手順の欠陥であって運用の逸脱ではない。
#
# 受容したトレードオフ:
#   - 複数のタイムゾーンにまたがる利用者の間では、辞書順整列と起票順が一致しない
#     （単独利用者による運用を前提として受容した）。
#   - 識別子が長くなる（日付8桁から時刻込み12桁へ）。
#   - 同一分に別ブランチで起票し、かつ双方が同じ連番を取った場合の重複は構造的に残る。
#     時刻部が分粒度である以上ここでは消せないため、検出は lint-adr.sh の識別子重複検査へ委ねる。
#
# 既存 ADR を遡及的に新形式へ移行する場合の規則: 各 ADR の時刻部は git の初回コミット時刻から
# 取る。時刻源は現在のパスに対する初回追加コミットの時刻を分粒度で採り、`--follow` は使わない
# （`--follow` の有無で結果が変わるファイルが実在し、うち一部は日付部まで変わるため、規則として
# 一意に定める）。同一時刻部に複数の ADR が落ちる場合、連番部は現行ファイル名の識別子の昇順で
# 01 から振り直し、旧連番の絶対値は引き継がず相対順序のみを引き継ぐ。
#
# 時刻部は環境変数 ADR_TIMESTAMP（YYYYMMDDHHMM の12桁）で固定できる。実時刻に依存すると
# 発番の検査が書けないため、本スクリプトのテストで用いる口である（通常の起票では設定しない）。
# 誤った値での発番を防ぐため、12桁であることに加えて暦としての妥当性（月 01-12・日 01-31・
# 時 00-23・分 00-59）も検査し、空文字を「未設定」へ畳まず不正として扱う。
#
# 使い方:
#   bash next-adr-id.sh [ADR_DIR]                        # 既定 ADR_DIR は docs/adr
#   ADR_TIMESTAMP=203104091530 bash next-adr-id.sh docs/adr   # テストでの時刻固定
#
# exit code:
#   0: 発番成功（識別子を stdout へ出力）
#   1: 同一時刻部の連番が上限 99 に達している、または ADR_TIMESTAMP の形式が不正
#   2: ADR_DIR が存在しない
set -euo pipefail

ADR_DIR="${1:-docs/adr}"
ADR_DIR="${ADR_DIR%/}"

if [ ! -d "$ADR_DIR" ]; then
    echo "エラー: ディレクトリが見つかりません: $ADR_DIR" >&2
    exit 2
fi

# `:-` ではなく `-` を使う。`:-` は空文字を「未設定」へ畳むため、ADR_TIMESTAMP="" が
# 黙って現在時刻へ落ち、変数展開に失敗した呼び出しを検出できなくなる。
timestamp="${ADR_TIMESTAMP-$(date +%Y%m%d%H%M)}"
if [[ ! "$timestamp" =~ ^[0-9]{4}(0[1-9]|1[0-2])(0[1-9]|[12][0-9]|3[01])([01][0-9]|2[0-3])[0-5][0-9]$ ]]; then
    echo "エラー: 時刻部が YYYYMMDDHHMM（暦として妥当な12桁）ではありません: $timestamp" >&2
    exit 1
fi

# 同一時刻部を持つ既存ファイルの連番部から最大番号を取る。
# 連番部が2桁数字でないファイル（旧形式・slug 直結等）は対象外として読み飛ばす。
max=0
shopt -s nullglob
for file in "$ADR_DIR"/ADR-"$timestamp"-*.md; do
    stem="$(basename "$file" .md)"
    seq="${stem#ADR-$timestamp-}"
    seq="${seq%%-*}"
    if [[ "$seq" =~ ^[0-9][0-9]$ ]]; then
        # 10# を付けて10進として解釈する（付けないと 08/09 が8進エラーになる）
        num=$((10#$seq))
        if [ "$num" -gt "$max" ]; then
            max="$num"
        fi
    fi
done
shopt -u nullglob

next=$((max + 1))
if [ "$next" -gt 99 ]; then
    echo "エラー: 同一時刻部 $timestamp の連番が上限 99 に達しています: $ADR_DIR" >&2
    exit 1
fi

printf 'ADR-%s-%02d\n' "$timestamp" "$next"
