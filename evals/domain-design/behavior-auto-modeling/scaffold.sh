cat > docs/library/event-storming.md <<'EOF'
# 図書館貸出 イベントストーミング

Design Level。対象は図書館カウンターでの蔵書の貸出・返却・延長と、延滞に伴う会員の利用停止。蔵書そのものの管理（登録・除籍・所在）は蔵書管理コンテキストの責務で、本コンテキストでは蔵書IDだけを扱う。会員登録は会員管理コンテキストで行われ、本コンテキストは登録済みの会員を利用可能の状態で受け取る。

## ドメインイベント

| # | イベント名（過去形） | 説明 |
|---|---|---|
| 1 | 貸出が開始された | 会員が蔵書1冊を借り出した。返却期限は貸出開始日から14日後 |
| 2 | 貸出期限が延長された | 返却期限を14日延ばした。延長は1件の貸出につき1回まで |
| 3 | 貸出が延滞した | 返却期限を過ぎても返却されていないことが判定された |
| 4 | 貸出が返却された | 会員が蔵書を返した（延滞中の返却を含む） |
| 5 | 会員が利用停止された | 延滞が発生したため、その会員への新規貸出を止めた |
| 6 | 会員の利用停止が解除された | その会員の延滞中の貸出が0件になった |

## コマンド

| # | コマンド名 | トリガーするイベント |
|---|---|---|
| 1 | 貸出を開始する | 貸出が開始された |
| 2 | 貸出期限を延長する | 貸出期限が延長された |
| 3 | 延滞を判定する | 貸出が延滞した |
| 4 | 返却を受け付ける | 貸出が返却された |
| 5 | 会員を利用停止にする | 会員が利用停止された |
| 6 | 利用停止を解除する | 会員の利用停止が解除された |

## アクター

| # | アクター名 | 種別 | 発行するコマンド |
|---|---|---|---|
| 1 | 司書 | 人間 | 貸出を開始する、返却を受け付ける |
| 2 | 会員 | 人間 | 貸出期限を延長する |
| 3 | 日次延滞判定 | 時間 | 延滞を判定する |
| 4 | 延滞停止ポリシー | ポリシー | 会員を利用停止にする |
| 5 | 停止解除ポリシー | ポリシー | 利用停止を解除する |

## 集約

### 会員

**責務**: 会員が本を借りられる資格（利用可能か利用停止中か）を管理する

**含むコマンド**: 会員を利用停止にする、利用停止を解除する

**含むイベント**: 会員が利用停止された、会員の利用停止が解除された

#### 状態遷移

```mermaid
stateDiagram-v2
    [*] --> 利用可能: 会員管理コンテキストから登録済みで受け取る
    利用可能 --> 利用停止中: 会員を利用停止にする
    利用停止中 --> 利用可能: 利用停止を解除する
```

| 状態 | 定義 | 遷移元 | 遷移先 |
|---|---|---|---|
| 利用可能 | 新規貸出を受けられる | -（会員管理コンテキスト） / 利用停止中 | 利用停止中 |
| 利用停止中 | 延滞中の貸出が1件以上あり、新規貸出を受けられない。停止日時を持つ | 利用可能 | 利用可能 |

### 貸出

**責務**: 蔵書1冊を会員1人に貸す1回の貸出のライフサイクルを管理する。貸出集約1件が蔵書1冊に対応する

**含むコマンド**: 貸出を開始する、貸出期限を延長する、延滞を判定する、返却を受け付ける

**含むイベント**: 貸出が開始された、貸出期限が延長された、貸出が延滞した、貸出が返却された

#### 状態遷移

```mermaid
stateDiagram-v2
    [*] --> 貸出中: 貸出を開始する [会員が利用可能 かつ 貸出上限に達していない]
    貸出中 --> 貸出中: 貸出期限を延長する [まだ延長していない]
    貸出中 --> 延滞中: 延滞を判定する [返却期限を過ぎた]
    貸出中 --> 返却済: 返却を受け付ける
    延滞中 --> 返却済: 返却を受け付ける
    返却済 --> [*]
```

| 状態 | 定義 | 遷移元 | 遷移先 |
|---|---|---|---|
| 貸出中 | 返却期限までに返却されていない。返却期限と延長の有無を持つ | - / 貸出中 | 貸出中 / 延滞中 / 返却済 |
| 延滞中 | 返却期限を過ぎても返却されていない。延滞判定日時を持つ | 貸出中 | 返却済 |
| 返却済 | 返却された。返却日時を持つ | 貸出中 / 延滞中 | 終了 |

## ポリシー

| ポリシー | トリガー | 実行するコマンド |
|---|---|---|
| 延滞停止ポリシー | 貸出が延滞した | 会員を利用停止にする（その会員がすでに利用停止中なら何もしない） |
| 停止解除ポリシー | 貸出が返却された | 利用停止を解除する（その会員の延滞中の貸出が0件になったときだけ） |

## ホットスポット

| # | ホットスポット | 関連する集約/イベント | 解消アクション |
|---|---|---|---|
| 1 | 貸出上限: 会員1人が同時に借りられるのは、貸出中と延滞中の貸出を合わせて5冊まで。6冊目の貸出を開始しようとしたら拒否する。上限の値と数え方は業務として確定済み。ただし貸出集約は1冊ごとに分かれているので、この上限は1人の会員に属する複数の貸出集約にまたがる件数の制約になる。どこでどう保証するかが整理できていない | 会員 / 貸出 / 貸出を開始する | ドメインモデリングで表現方法を決める |
| 2 | 延長は1件の貸出につき1回まで。延長済みの貸出をさらに延長しようとしたら拒否する | 貸出 / 貸出期限を延長する | ドメインモデリングで型に落とす |
| 3 | 利用停止中の会員には新規貸出をしない | 会員 / 貸出を開始する | ドメインモデリングで型に落とす |

## 用語集（ユビキタス言語）

| 用語 | 定義 | 備考 |
|---|---|---|
| 会員 | 図書館の利用登録をした人。会員IDで識別する | 登録は会員管理コンテキスト |
| 蔵書 | 図書館が所蔵する本の1冊。蔵書IDで識別する | 管理は蔵書管理コンテキスト |
| 貸出 | 蔵書1冊を会員1人に貸す1回の取引 | 貸出IDで識別する |
| 返却期限 | 貸出開始日から14日後。延長すると14日延びる | |
| 延長 | 返却期限を14日延ばすこと。1件の貸出につき1回まで | 延滞中は延長できない |
| 延滞 | 返却期限を過ぎても返却されていない状態 | 日次延滞判定で判定する |
| 利用停止 | 延滞中の貸出がある会員への新規貸出を止めること | 延滞中の貸出が0件になると解除 |
| 貸出上限 | 会員1人が同時に持てる貸出（貸出中＋延滞中）の件数の上限。5冊 | |
