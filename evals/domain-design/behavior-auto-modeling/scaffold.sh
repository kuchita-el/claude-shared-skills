# - dd-04: ホットスポット1「貸出上限（会員1人あたり貸出中＋延滞中で5冊まで）」は、
#   会員ごとに複数の貸出集約インスタンスへまたがる件数の制約で、状態型の OR では排除できない。
#   事実（上限値・数える状態・拒否の時点）は入力に揃えてあり、「入力にない事実を補う」停止には当たらない。
#   手順書どおりなら「型で表せなかった不変条件」へ記録して生成を完了する。
# - dd-01/dd-02: 貸出集約は 貸出中→延滞中→返却済 の遷移を持つ。全コマンドに発火イベントを与えてあるので、
#   `イベント:` 欄へ遷移先の状態名を書く（旧規約）か発火イベントのみ書く（新規約）かが分かれる。
# - 型で表せる対照として、ホットスポット2（延長は1回まで）・3（利用停止中の会員には貸さない）を置く。
